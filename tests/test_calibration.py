"""Calibration tests.

Market data are generated by the independent COS oracle from known parameters, so the
truth is the parameter set itself, not the package's output.
"""

import numpy as np
import pytest
from scipy.stats import chi2
from scipy.stats import f as f_dist

import reference as R
from conftest import REF, STRESS, model_args
from hestonlib.analytic import heston_call
from hestonlib.calibration import LOWER, NAMES, UPPER, Surface, calibrate
from hestonlib.params import HestonParams

MATS = np.array([0.25, 0.5, 1.0, 2.0])
STRIKES = np.array([80.0, 90.0, 95.0, 100.0, 105.0, 110.0, 120.0])


def _surface(d, iv_noise=0.0, seed=0, tight=False):
    """Market calls from the COS oracle. ``tight`` uses N = 2^17, L = 192, which
    test_implied_vol shows converged to < 1e-12 by doubling."""
    kw = dict(N=2**17, L=192.0, adaptive=False) if tight else {}
    prices = np.array([R.cos_call(d["S0"], STRIKES, T, *model_args(d), **kw) for T in MATS])
    s = Surface(d["S0"], d["r"], d["q"], MATS, STRIKES, prices)
    if iv_noise:
        iv = s.ivs() + iv_noise * np.random.default_rng(seed).standard_normal(prices.shape)
        prices = np.array([R.bs_price(d["S0"], STRIKES, T, d["r"], d["q"], v) for T, v in zip(MATS, iv)])
        s = Surface(d["S0"], d["r"], d["q"], MATS, STRIKES, prices)
    return s


def _truth(d):
    return np.array([d[n] for n in NAMES])


def test_bounds_contain_the_test_parameter_sets():
    for d in (REF, STRESS):
        assert np.all(LOWER < _truth(d)) and np.all(_truth(d) < UPPER)


@pytest.mark.parametrize("d", [REF, STRESS], ids=["ref", "stress"])
def test_noise_free_recovery(d):
    """Data from the converged COS (error < 1e-12). At the true parameters each residual
    is then bounded by (err_j + 1e-12) / vega_j, where err_j is the Lewis pricer's error
    estimate at quote j (test_implied_vol shows it bounds the true error). To first order,
    |x_hat - x_true|_2 <= (|dr|_2 + |r_final|_2) / sigma_min(J). Tolerance: twice that
    (factor 2 for the linearization), on every parameter. The start is far from the
    truth. STRESS violates Feller (ratio 0.09); the calibration must report it, not impose it."""
    s = _surface(d, tight=True)
    res = calibrate(s, x0=(0.06, 1.0, 0.06, 0.5, -0.4))
    vega = s.vegas()
    p_true = HestonParams(**d)
    err = np.array([heston_call(STRIKES, T, p_true, return_error=True)[1] for T in MATS])
    dr = np.sqrt(np.sum(((err + 1e-12) / vega) ** 2))
    sig_min = np.linalg.svd(res.jac, compute_uv=False).min()
    tol = 2 * (dr + np.linalg.norm(res.residuals)) / sig_min
    err = np.abs(res.x - _truth(d))
    assert np.all(err < tol), (err, tol)
    assert tol < 1e-6  # the bound must be informative
    assert res.success and res.at_bound == ()
    assert res.feller_ratio == pytest.approx(2 * d["kappa"] * d["theta"] / d["xi"] ** 2, rel=1e-6)
    # Reported IV errors come from two exact inversions (model and market); they must equal
    # the vega-weighted residuals up to twice the inversion accuracy (64 eps S0 / vega + 1e-13
    # each, test_implied_vol); the second-order Taylor term is O(r^2) ~ 1e-20 here.
    inv_tol = 2 * (64 * np.finfo(float).eps * s.S0 / vega.ravel() + 1e-13)
    assert np.all(np.abs(res.iv_errors.ravel() - res.residuals) < inv_tol)


def test_noisy_recovery_is_consistent_with_reported_se():
    """IV noise iid N(0, 0.002^2) on the REF surface (28 quotes), one seed. Each parameter error must be
    within 4 of its reported SE (sqrt of the diagonal of s^2 (J^T J)^{-1}). Since s^2 is
    estimated with 23 dof, each z is t_23: P(|t_23| > 4) = 5.6e-4, so the false-failure
    probability over five parameters is at most 2.8e-3 if the linearized model holds. The residual
    scale s (from exact IV errors) must match the noise: s^2 / 0.002^2 lies within the
    chi2_{23}/23 0.05% and 99.95% quantiles."""
    noise = 0.002
    res = calibrate(_surface(REF, noise, seed=7))
    delta = res.x - _truth(REF)
    z = delta / res.se
    assert np.all(np.abs(z) < 4), z
    # The reported covariance diag(se) corr diag(se) must be right in size, not only not too
    # small. Under the linear model delta' (J^T J) delta / sigma^2 is chi2_5, independent of
    # s^2 / sigma^2 ~ chi2_23 / 23, so the Mahalanobis distance with the estimated s^2 is
    # 5 F(5, 23). Its 0.05% and 99.95% quantiles are 0.149 and 34.0; the lower one catches an
    # overstated SE (for example a missing s^2 factor).
    cov = np.outer(res.se, res.se) * res.corr
    maha = float(delta @ np.linalg.solve(cov, delta))
    lo_m, hi_m = 5 * f_dist.ppf([0.0005, 0.9995], 5, m_dof := res.iv_errors.size - 5)
    assert lo_m < maha < hi_m, maha
    m = res.iv_errors.size
    s2 = np.sum(res.iv_errors**2) / (m - 5)
    lo, hi = chi2.ppf([0.0005, 0.9995], m - 5) / (m - 5)
    assert lo < s2 / noise**2 < hi, s2 / noise**2


def test_unresolvable_quotes_are_rejected():
    """A quote at the no-arbitrage lower bound has no implied vol: calibration refuses it."""
    s = _surface(REF)
    prices = s.prices.copy()
    T, K = MATS[0], STRIKES[0]
    prices[0, 0] = max(REF["S0"] - K * np.exp(-REF["r"] * T), 0.0)
    with pytest.raises(ValueError):
        calibrate(Surface(s.S0, s.r, s.q, s.maturities, s.strikes, prices))


def test_short_dated_wings_do_not_crash_and_unresolved_ivs_are_counted():
    """Regression (stage 4 review): a 1.5-day maturity with wing quotes priced by BS at 90%
    vol. Every market IV resolves, but Heston prices at those wings sit within the
    quadrature error of zero (and may be slightly negative). The fit must not raise, and
    model IVs that the model price cannot resolve are NaN and counted, never silently
    dropped. Consistency: the count equals the number of NaNs, and RMSE uses the rest."""
    S0, r, q = REF["S0"], REF["r"], REF["q"]
    mats = np.array([0.004, 0.25, 1.0])
    strikes = np.array([70.0, 100.0, 130.0])
    rows = [R.bs_price(S0, strikes, mats[0], r, q, 0.9)]
    rows += [R.cos_call(S0, strikes, T, *model_args(REF)) for T in mats[1:]]
    res = calibrate(Surface(S0, r, q, mats, strikes, np.array(rows)))
    nan = np.isnan(res.iv_errors)
    assert res.n_iv_unresolved == int(nan.sum())
    assert res.n_iv_unresolved >= 1  # the regime the regression is about does occur
    assert np.isfinite(res.iv_rmse)
    assert res.iv_rmse == pytest.approx(np.sqrt(np.mean(res.iv_errors[~nan] ** 2)), rel=1e-12)
